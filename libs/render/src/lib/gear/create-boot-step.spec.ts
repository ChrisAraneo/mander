import { describe, expect, it } from 'vitest';

import { drawRecorded } from '../../test/draw-recorded';
import { createBootStep } from './create-boot-step';

describe('createBootStep', () => {
  it('should draw the cloud boot filling the box when the box starts at the corner', () => {
    const calls = drawRecorded(createBootStep(0, 0, 32));

    expect(calls).toEqual([
      'save()',
      'set fillStyle(#F2FAFF)',
      'beginPath()',
      'moveTo(13.44, 25.92)',
      'ellipse(8.64, 25.92, 4.8, 2.88, 0, 0, 6.2832)',
      'moveTo(22.08, 27.2)',
      'ellipse(16, 27.2, 6.08, 3.52, 0, 0, 6.2832)',
      'moveTo(27.84, 25.6)',
      'ellipse(23.36, 25.6, 4.48, 2.56, 0, 0, 6.2832)',
      'fill()',
      'restore()',
      'save()',
      'beginPath()',
      'moveTo(12.8, 4.48)',
      'lineTo(20.48, 4.48)',
      'lineTo(20.48, 16)',
      'lineTo(22.08, 18.88)',
      'lineTo(22.08, 22.4)',
      'lineTo(7.68, 22.4)',
      'lineTo(6.72, 19.84)',
      'lineTo(11.52, 16.32)',
      'lineTo(12.8, 13.76)',
      'closePath()',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'createLinearGradient(16, 4.48, 16, 22.4)',
      'addColorStop(0, #F4FBFF)',
      'addColorStop(0.55, #9FD2F0)',
      'addColorStop(1, #2F5C7E)',
      'set fillStyle(gradient)',
      'fill()',
      'restore()',
      'set fillStyle(#5C7EA0)',
      'beginPath()',
      'roundRect(6.4, 21.76, 16.32, 2.24, 0.96)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
      'set fillStyle(#F4FBFF)',
      'beginPath()',
      'roundRect(11.84, 3.52, 9.6, 2.88, 1.28)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
      'set fillStyle(#2F5C7E)',
      'beginPath()',
      'roundRect(10.88, 16, 10.56, 1.92, 0.64)',
      'fill()',
    ]);
  });

  it('should draw the cloud boot moved and enlarged when the box is shifted and bigger', () => {
    const calls = drawRecorded(createBootStep(10, 5, 64));

    expect(calls).toEqual([
      'save()',
      'set fillStyle(#F2FAFF)',
      'beginPath()',
      'moveTo(36.88, 56.84)',
      'ellipse(27.28, 56.84, 9.6, 5.76, 0, 0, 6.2832)',
      'moveTo(54.16, 59.4)',
      'ellipse(42, 59.4, 12.16, 7.04, 0, 0, 6.2832)',
      'moveTo(65.68, 56.2)',
      'ellipse(56.72, 56.2, 8.96, 5.12, 0, 0, 6.2832)',
      'fill()',
      'restore()',
      'save()',
      'beginPath()',
      'moveTo(35.6, 13.96)',
      'lineTo(50.96, 13.96)',
      'lineTo(50.96, 37)',
      'lineTo(54.16, 42.76)',
      'lineTo(54.16, 49.8)',
      'lineTo(25.36, 49.8)',
      'lineTo(23.44, 44.68)',
      'lineTo(33.04, 37.64)',
      'lineTo(35.6, 32.52)',
      'closePath()',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'createLinearGradient(42, 13.96, 42, 49.8)',
      'addColorStop(0, #F4FBFF)',
      'addColorStop(0.55, #9FD2F0)',
      'addColorStop(1, #2F5C7E)',
      'set fillStyle(gradient)',
      'fill()',
      'restore()',
      'set fillStyle(#5C7EA0)',
      'beginPath()',
      'roundRect(22.8, 48.52, 32.64, 4.48, 1.92)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
      'set fillStyle(#F4FBFF)',
      'beginPath()',
      'roundRect(33.68, 12.04, 19.2, 5.76, 2.56)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
      'set fillStyle(#2F5C7E)',
      'beginPath()',
      'roundRect(31.76, 37, 21.12, 3.84, 1.28)',
      'fill()',
    ]);
  });
});
