import { describe, expect, it } from 'vitest';

import { drawRecorded } from '../../test/draw-recorded';
import { createHelmetStep } from './create-helmet-step';

describe('createHelmetStep', () => {
  it('should draw the titanium helmet filling the box when the box starts at the corner', () => {
    const calls = drawRecorded(createHelmetStep(0, 0, 32));

    expect(calls).toEqual([
      'save()',
      'set fillStyle(#9AA7B8)',
      'beginPath()',
      'roundRect(8.96, 16, 14.08, 5.12, 1.92)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
      'beginPath()',
      'moveTo(6.08, 16.64)',
      'arc(16, 16.64, 9.92, 3.1416, 6.2832)',
      'closePath()',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'createLinearGradient(16, 6.72, 16, 16.64)',
      'addColorStop(0, #F0F5FA)',
      'addColorStop(0.5, #9AA7B8)',
      'addColorStop(1, #2E3743)',
      'set fillStyle(gradient)',
      'fill()',
      'restore()',
      'set fillStyle(#F0F5FA)',
      'beginPath()',
      'roundRect(5.12, 15.04, 21.76, 2.56, 1.28)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
      'set fillStyle(#141A24)',
      'beginPath()',
      'roundRect(9.28, 11.52, 13.44, 2.56, 0.96)',
      'fill()',
      'set fillStyle(#2E3743)',
      'beginPath()',
      'roundRect(15.04, 5.12, 1.92, 3.84, 0.96)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
    ]);
  });

  it('should draw the titanium helmet moved and enlarged when the box is shifted and bigger', () => {
    const calls = drawRecorded(createHelmetStep(10, 5, 64));

    expect(calls).toEqual([
      'save()',
      'set fillStyle(#9AA7B8)',
      'beginPath()',
      'roundRect(27.92, 37, 28.16, 10.24, 3.84)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
      'beginPath()',
      'moveTo(22.16, 38.28)',
      'arc(42, 38.28, 19.84, 3.1416, 6.2832)',
      'closePath()',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'createLinearGradient(42, 18.44, 42, 38.28)',
      'addColorStop(0, #F0F5FA)',
      'addColorStop(0.5, #9AA7B8)',
      'addColorStop(1, #2E3743)',
      'set fillStyle(gradient)',
      'fill()',
      'restore()',
      'set fillStyle(#F0F5FA)',
      'beginPath()',
      'roundRect(20.24, 35.08, 43.52, 5.12, 2.56)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
      'set fillStyle(#141A24)',
      'beginPath()',
      'roundRect(28.56, 28.04, 26.88, 5.12, 1.92)',
      'fill()',
      'set fillStyle(#2E3743)',
      'beginPath()',
      'roundRect(40.08, 15.24, 3.84, 7.68, 1.92)',
      'set strokeStyle(#0f0d16)',
      'set lineWidth(4)',
      'set lineJoin(round)',
      'stroke()',
      'fill()',
    ]);
  });
});
